import { test } from "node:test"
import assert from "node:assert/strict"

import {
	dmarcPasses,
	findTrustedAuthResults,
	isAutoGenerated,
	normalizeAddress,
	stripQuoted,
} from "../src/core/reply-parse.ts"

test("stripQuoted: plain reply survives", () => {
	assert.equal(stripQuoted("yes, go ahead"), "yes, go ahead")
	assert.equal(stripQuoted("  line one\nline two  "), "line one\nline two")
})

test("stripQuoted: cuts at an 'On … wrote:' boundary", () => {
	const body = ["Sounds good, ship it.", "", "On Tue, 3 Jun 2025 at 09:12, pi <pi@example.com> wrote:", "> do the thing"].join("\n")
	assert.equal(stripQuoted(body), "Sounds good, ship it.")
})

test("stripQuoted: cuts at Outlook original-message and underscore banners", () => {
	const a = ["approve", "-----Original Message-----", "From: pi"].join("\n")
	assert.equal(stripQuoted(a), "approve")
	const b = ["approve", "______________________________", "older text"].join("\n")
	assert.equal(stripQuoted(b), "approve")
})

test("stripQuoted: stops at a quoted block even without a banner", () => {
	assert.equal(stripQuoted("do it\n> previous message\n> more"), "do it")
})

test("stripQuoted: stops at an RFC 3676 signature", () => {
	const body = ["thanks", "", "-- ", "Ada", "CEO, Example"].join("\n")
	assert.equal(stripQuoted(body), "thanks")
})

test("stripQuoted: an entirely-quoted body yields empty", () => {
	// No new content: the pipeline rejects `""` as empty-body rather than
	// replaying the agent's own quoted output back at it.
	assert.equal(stripQuoted("> only quoted\n> text here"), "")
	assert.equal(stripQuoted("\n\n"), "")
})

test("stripQuoted: tolerates CRLF and empty input", () => {
	assert.equal(stripQuoted("yes\r\n\r\nOn x wrote:\r\n> q"), "yes")
	assert.equal(stripQuoted(""), "")
})

test("normalizeAddress: display names, case, bare addresses", () => {
	assert.equal(normalizeAddress("Ada <User@Example.COM>"), "user@example.com")
	assert.equal(normalizeAddress("user@example.com"), "user@example.com")
	assert.equal(normalizeAddress("  <a@b.co> "), "a@b.co")
	assert.equal(normalizeAddress("not an address"), undefined)
	assert.equal(normalizeAddress(""), undefined)
	assert.equal(normalizeAddress(undefined), undefined)
})

test("isAutoGenerated: catches loops and bulk mail", () => {
	assert.equal(isAutoGenerated({ autoSubmitted: "auto-replied" }), true)
	assert.equal(isAutoGenerated({ autoSubmitted: "no" }), false)
	assert.equal(isAutoGenerated({ precedence: "Bulk" }), true)
	assert.equal(isAutoGenerated({ listId: "<list.example.com>" }), true)
	// "All" is what some gateways stamp on human mail, so it is not a signal on its own.
	assert.equal(isAutoGenerated({ autoResponseSuppress: "All" }), false)
	assert.equal(isAutoGenerated({ autoResponseSuppress: "OOF" }), true)
	assert.equal(isAutoGenerated({}), false)
})

test("findTrustedAuthResults: only the pinned authserv-id is trusted", () => {
	const headers = {
		authResults: [
			"mx.example.com; spf=pass smtp.mailfrom=example.com; dmarc=pass header.from=example.com",
			"evil.example.net; dmarc=pass header.from=you@example.com",
		],
	}
	const ar = findTrustedAuthResults(headers, "mx.example.com")
	assert.ok(ar)
	assert.equal(dmarcPasses(ar), true)
	// An unpinned id must not be selected even though it also says pass.
	assert.equal(findTrustedAuthResults(headers, "other.example.com"), undefined)
})

test("findTrustedAuthResults: a forged top header from the sender is ignored", () => {
	// Attacker prepends their own AR claiming pass, but with their own authserv-id.
	const headers = {
		authResults: [
			"attacker.example; dmarc=pass header.from=you@example.com",
			"mx.example.com; spf=fail; dmarc=fail header.from=you@example.com",
		],
	}
	const ar = findTrustedAuthResults(headers, "mx.example.com")
	assert.ok(ar)
	assert.equal(dmarcPasses(ar), false, "must read our relay's verdict, not the sender's")
})

test("dmarcPasses: does not match dmarc=fail or dmarc=none", () => {
	assert.equal(dmarcPasses("mx; dmarc=fail"), false)
	assert.equal(dmarcPasses("mx; dmarc=none"), false)
	assert.equal(dmarcPasses("mx; dmarc=pass header.from=a"), true)
})

// --- Microsoft-style bare Authentication-Results (no authserv-id) ---------

test("a bare AR header with no authserv-id is used when nothing is pinned", () => {
	// This is what Microsoft's consumer relay actually emits on delivery.
	const ar = "spf=pass (sender IP is 40.92.1.1) smtp.mailfrom=hotmail.com; dkim=pass; dmarc=pass action=none header.from=hotmail.com; compauth=pass reason=100"
	const found = findTrustedAuthResults({ authResults: [ar] }, undefined)
	assert.equal(found, ar)
	assert.equal(dmarcPasses(ar), true)
})

test("a bare AR that fails dmarc is still rejected", () => {
	const ar = "spf=fail; dmarc=fail action=oreject header.from=hotmail.com"
	const found = findTrustedAuthResults({ authResults: [ar] }, undefined)
	assert.equal(dmarcPasses(String(found)), false)
})

test("the topmost header wins, so a sender-forged one underneath cannot authorize", () => {
	const headers = {
		authResults: [
			"spf=fail; dmarc=fail header.from=hotmail.com",
			"attacker.example; dmarc=pass header.from=hotmail.com",
		],
	}
	const found = findTrustedAuthResults(headers, undefined)
	assert.equal(dmarcPasses(String(found)), false, "the relay's verdict is first, not the sender's")
})

test("a pinned authserv-id that is absent fails closed rather than falling back", () => {
	const bare = "spf=pass; dmarc=pass header.from=hotmail.com"
	assert.equal(findTrustedAuthResults({ authResults: [bare] }, "mx.example.com"), undefined)
})

test("the Outlook mobile signature is stripped", () => {
	// Verbatim tail of a real reply from an Outlook.com account.
	assert.equal(stripQuoted("It works!\n\n获取Outlook for Android<https://aka.ms/AAb9ysg>"), "It works!")
	assert.equal(stripQuoted("Looks good\n\nGet Outlook for iOS<https://aka.ms/AAb9ysg>"), "Looks good")
	assert.equal(stripQuoted("Get Outlook for Android"), "", "a signature with no content leaves nothing")
})

test("QQ and 163 quoted history is stripped", () => {
	// The Chinese clients are the primary target for this package, and their quote banners were
	// not in the boundary list: the agent was fed its own previous output every turn.
	const reply = [
		"yes, go ahead",
		"",
		"------------------ 原始邮件 ------------------",
		"发件人: pi <pi@qq.com>",
		"主题: [pi:abc123] pi: proj @ box",
		"",
		"done",
	].join("\n")
	assert.equal(stripQuoted(reply).trim(), "yes, go ahead")

	const wechat = ["ship it", "", "在 2025年6月3日 09:12，pi <pi@qq.com> 写道：", "> done"].join("\n")
	assert.equal(stripQuoted(wechat).trim(), "ship it")
})

test("X-Auto-Response-Suppress alone does not make a message machine-generated", () => {
	// Some Outlook and gateway configurations stamp this header on ordinary mail; treating any
	// presence as an auto-reply silently rejected genuine replies.
	assert.equal(isAutoGenerated({ autoResponseSuppress: "None" }), false)
	assert.equal(isAutoGenerated({ autoResponseSuppress: "All" }), false)
	assert.equal(isAutoGenerated({ autoResponseSuppress: "OOF" }), true, "out-of-office still counts")
	assert.equal(isAutoGenerated({ autoResponseSuppress: "AutoReply" }), true)
})
