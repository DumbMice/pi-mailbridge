// Reply parsing: turn a raw mail body into the single line of human intent.
//
// Quoted-text stripping is the fragile part of any email bridge — every client
// quotes differently. The approach here is deliberately blunt: cut at the first
// recognizable quote boundary and accept the remainder. Being clever (nested
// quoting, locale heuristics) loses more than it gains.
//
// Outbound mail instructs the human to reply *above* the quoted text, so the
// top of the body is the answer.

/** Markers that begin a quoted/original section. Matched case-insensitively. */
const QUOTE_BOUNDARIES: RegExp[] = [
	// "On Tue, 3 Jun 2025 at 09:12, pi <pi@example.com> wrote:"
	/^\s*On\b.{0,200}\bwrote:\s*$/i,
	// Outlook / web clients
	/^\s*-{2,}\s*Original Message\s*-{2,}\s*$/i,
	/^\s*_{10,}\s*$/,
	/^\s*From:\s.+$/i,
	// "> " quoted block start (BEFORE the boundary scan strips lines)
	/^\s*>/,
	// Forwarded-message banner
	/^\s*-{2,}\s*Forwarded message\s*-{2,}\s*$/i,
	// Mobile clients
	/^\s*Sent from my\b/i,
	// Outlook mobile app signature, in either the English or the Chinese build.
	/^\s*(?:获取|Get)\s*Outlook\s*for\s+(?:Android|iOS|iPhone|iPad)\b/i,
]

/** Signature delimiter per RFC 3676 §4.3 — "dash dash space". */
const SIGNATURE_DELIM = /^--\s*$/

function normalizeNewlines(text: string): string {
	return text.replace(/\r\n?/g, "\n")
}

/**
 * Strip quoted text and signature from a reply body.
 *
 * Returns the top-of-mail content, or `""` when the message carried nothing
 * new (e.g. the body was entirely quoted). Callers must treat `""` as "no
 * instruction" and reject — re-injecting the quoted original into the agent
 * would just replay the agent's own output back at it.
 */
export function stripQuoted(raw: string): string {
	if (!raw) return ""
	const text = normalizeNewlines(raw)
	const lines = text.split("\n")
	const kept: string[] = []

	for (let i = 0; i < lines.length; i++) {
		const line = lines[i]!
		if (SIGNATURE_DELIM.test(line)) break
		if (QUOTE_BOUNDARIES.some((re) => re.test(line))) break
		kept.push(line)
	}

	// Drop trailing blank lines.
	while (kept.length > 0 && kept[kept.length - 1]!.trim() === "") kept.pop()

	return kept.join("\n").trim()
}

export interface HeaderLike {
	from?: string
	subject?: string
	/** Every `Authentication-Results` value, in the order received (top first). */
	authResults?: string[]
	/** `Message-ID` of this message. Used to recognise our own mail when it comes back. */
	messageId?: string
	/** `In-Reply-To`, the message this one directly answers. */
	inReplyTo?: string
	/** `References`, the ancestor chain. */
	references?: string[]
	/** `Auto-Submitted`, `Precedence`, `X-Auto-Response-Suppress`, `List-Id`. */
	autoSubmitted?: string
	precedence?: string
	autoResponseSuppress?: string
	listId?: string
}

/**
 * Reduce `"Name" <User@Example.COM>` to `user@example.com`.
 * Handles bare addresses, angle-addresses, and display names containing commas.
 */
export function normalizeAddress(input: string | undefined | null): string | undefined {
	if (!input) return undefined
	const angle = /<([^<>]+)>\s*$/.exec(input)
	const candidate = (angle?.[1] ?? input).trim()
	// Anything with whitespace left is a display name we could not parse.
	if (!candidate || /\s/.test(candidate)) return undefined
	if (!/^[^@\s]+@[^@\s]+$/.test(candidate)) return undefined
	return candidate.toLowerCase()
}

/**
 * Is this message machine-generated? Replying to one of these is how mail loops
 * start (out-of-office → us → out-of-office → …).
 */
export function isAutoGenerated(headers: HeaderLike): boolean {
	const auto = headers.autoSubmitted?.trim().toLowerCase()
	if (auto && auto !== "no") return true
	const prec = headers.precedence?.trim().toLowerCase()
	if (prec === "bulk" || prec === "junk" || prec === "list") return true
	if (headers.autoResponseSuppress?.trim()) return true
	if (headers.listId?.trim()) return true
	return false
}

/**
 * Find the `Authentication-Results` header that our own relay added.
 *
 * Headers are prepended as a message traverses MTAs, so the TOPMOST
 * `Authentication-Results` is the one the final hop (your provider) wrote on
 * delivery. A sender that includes a forged header ends up *below* it, which is
 * why topmost-wins defeats header forgery — see docs/SECURITY.md §2.1.
 *
 * `authservId` pins it further when a provider writes one. It is optional
 * because Microsoft's consumer relay emits bare headers with no authserv-id
 * (`Authentication-Results: spf=pass ...; dmarc=pass ...`), and requiring a match
 * there would reject every piece of genuine mail.
 */
export function findTrustedAuthResults(headers: HeaderLike, authservId?: string): string | undefined {
	const values = headers.authResults ?? []
	if (values.length === 0) return undefined

	const wanted = authservId?.trim().toLowerCase()
	if (!wanted) return values[0] // topmost = the delivering relay's

	for (const value of values) {
		const id = /^\s*([^\s;]+)/.exec(value)?.[1]?.toLowerCase()
		if (id === wanted) return value
	}
	// Pinned but absent: do not silently fall back to an unverified header.
	return undefined
}

/** `dmarc=pass` inside a specific AR header value. */
export function dmarcPasses(authResultsValue: string): boolean {
	return /\bdmarc\s*=\s*pass\b/i.test(authResultsValue)
}
